    heatmap = sns.clustermap(data=z_scores_df, cmap=cmap, annot=False, fmt=".1f", linewidths=0, linecolor='black', yticklabels=True, vmin=-1, vmax=1, col_cluster=False, cbar_pos=(0.01, 0.82, 0.09, 0.09))

