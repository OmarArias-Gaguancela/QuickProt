def longest_common_prefix(strings):
    if not strings: return ""
    prefix = strings[0]
    for s in strings[1:]:
        while not s.startswith(prefix):
            prefix = prefix[:-1]
            if not prefix: break
    return prefix

def longest_common_suffix(strings):
    if not strings: return ""
    suffix = strings[0]
    for s in strings[1:]:
        while not s.endswith(suffix):
            suffix = suffix[1:]
            if not suffix: break
    return suffix

